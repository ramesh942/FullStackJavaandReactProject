// Operator Example = // Example of using Arthmatic operators in a conditional statement
let a = 10;
let b = 5;
let sum = a + b; // Addition
console.log("Sum:", sum); // Output: Sum: 15
 
//Strick Equality Example = // Example of using strict equality operator in a conditional statement
if (a === b) {
    console.log("Strict equality: true");
} else {
    console.log("Strict equality: false"); // Output: Strict equality: false
}

//Equality Example = // Example of using equality operator in a conditional statement
if (a == b) {
    console.log("Equality: true");
}
else {
    console.log("Equality: false"); // Output: Equality: false
}

//Logical AND Example = // Example of using logical AND operator in a conditional statement
if (a > 0 && b > 0) {
    console.log("Both a and b are positive numbers."); // Output: Both a and b are positive numbers.
}
else {
    console.log("At least one of a or b is not a positive number.");
}

//Logical OR Example = // Example of using logical OR operator in a conditional statement

if (a > 0 || b > 0) {
    console.log("At least one of a or b is a positive number."); // Output: At least one of a or b is a positive number.
}
else {
    console.log("Neither a nor b is a positive number.");
}

